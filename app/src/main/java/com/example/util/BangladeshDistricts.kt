            "নেত্রকোণা", "netrokona", "netrakona" -> "নেত্রকোণা"
            else -> ""
        }
        if (directMatch.isNotBlank()) return directMatch

        // Check if any canonical district name is contained in the input
        for (d in districts) {
            if (trimmed.contains(d) || clean.contains(d)) return d
        }

        return trimmed
    }

    private fun cleanLocationName(input: String): String {
        return input.trim()
            .replace("পোস্ট অফিস", "")
            .replace("ডাকঘর", "")
            .replace("উপজেলা", "")
            .replace("থানা", "")
            .replace("জেলা", "")
            .replace("District", "", ignoreCase = true)
            .replace("Upazila", "", ignoreCase = true)
            .replace("Thana", "", ignoreCase = true)
            .replace("Post Office", "", ignoreCase = true)
            .replace("Post", "", ignoreCase = true)
            .replace(":", "")
            .replace("-", "")
            .trim()
    }

    fun lookupPostCode(district: String, upazila: String = "", postOffice: String = ""): String {
        val normDist = normalizeDistrictName(district)
        val cleanPo = cleanLocationName(postOffice)
        val rawPo = postOffice.trim()
        val cleanUpazila = cleanLocationName(upazila)
        val rawUpazila = upazila.trim()

        // Helper to format valid 4-digit code
        fun formatValidCode(code: String?): String? {
            if (code == null) return null
            val trimmed = code.trim()
            if (trimmed.length == 4 && trimmed.all { it.isDigit() || it in '০'..'৯' }) {
                return BanglaTextValidator.toBanglaDigits(trimmed)
            }
            return null
        }

        // 1. Scoped search inside the specified district
        if (normDist.isNotBlank()) {
            val distMap = locationPostCodesByDistrict[normDist]
            if (distMap != null) {
                // Check post office exact match
                if (rawPo.isNotBlank()) {
                    formatValidCode(distMap[rawPo])?.let { return it }
                }
                if (cleanPo.isNotBlank()) {
                    formatValidCode(distMap[cleanPo])?.let { return it }
                }
                // Check post office partial match in this district
                if (cleanPo.isNotBlank() && cleanPo.length >= 2) {
                    val match = distMap.entries.firstOrNull { (k, _) ->
                        k.contains(cleanPo) || cleanPo.contains(k)
                    }
                    if (match != null) {
                        formatValidCode(match.value)?.let { return it }
                    }
                }

                // Check upazila exact match
                if (rawUpazila.isNotBlank()) {
                    formatValidCode(distMap[rawUpazila])?.let { return it }
                }
                if (cleanUpazila.isNotBlank()) {
                    formatValidCode(distMap[cleanUpazila])?.let { return it }
                }
                // Check upazila partial match in this district
                if (cleanUpazila.isNotBlank() && cleanUpazila.length >= 2) {
                    val match = distMap.entries.firstOrNull { (k, _) ->
                        k.contains(cleanUpazila) || cleanUpazila.contains(k)
                    }
                    if (match != null) {
                        formatValidCode(match.value)?.let { return it }
                    }
                }
            }

            // District default headquarter code
            formatValidCode(districtHeadquarters[normDist])?.let { return it }
        }

        // 2. Fallback search across all districts if district was unspecified or not matched
        if (rawPo.isNotBlank() || cleanPo.isNotBlank()) {
            val searchKey = if (cleanPo.isNotBlank()) cleanPo else rawPo
            for ((_, distMap) in locationPostCodesByDistrict) {
                formatValidCode(distMap[searchKey])?.let { return it }
                if (searchKey.length >= 3) {
                    val match = distMap.entries.firstOrNull { (k, _) ->
                        k.contains(searchKey) || searchKey.contains(k)
                    }
                    if (match != null) {
                        formatValidCode(match.value)?.let { return it }
                    }
                }
            }
        }

        if (rawUpazila.isNotBlank() || cleanUpazila.isNotBlank()) {
            val searchKey = if (cleanUpazila.isNotBlank()) cleanUpazila else rawUpazila
            for ((_, distMap) in locationPostCodesByDistrict) {
                formatValidCode(distMap[searchKey])?.let { return it }
                if (searchKey.length >= 3) {
                    val match = distMap.entries.firstOrNull { (k, _) ->
                        k.contains(searchKey) || searchKey.contains(k)
                    }
                    if (match != null) {
                        formatValidCode(match.value)?.let { return it }
                    }
                }
            }
        }

        return ""
    }
